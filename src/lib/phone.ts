/**
 * Телефон: одна логика на форму и на сервер.
 *
 * Зачем отдельный модуль. Раньше поле принимало что угодно — буквы, слова,
 * десять цифр без кода страны. Клиент проверял только «цифр не меньше
 * десяти», сервер — регуляркой на 10–20 любых символов. Из-за этого
 * «+7 700 000 00 0» и «87000000000» проходили как разные номера, а опечатка
 * вида «…00O» (с буквой O) уезжала администратору.
 *
 * КОД СТРАНЫ НЕ УГАДЫВАЕТСЯ, А ЗАДАН ЖЁСТКО. Первая версия маски пыталась
 * понять по вводу, набрал человек код страны или нет, и досочиняла «7», если
 * цифр было десять. На тестах это давало худший из возможных дефектов:
 * недонабранный номер «+7 700 123 45 6» превращался в «+7 777 001 234 56» —
 * маска молча дописывала лишнюю семёрку, и человек отправлял чужой номер.
 * Поэтому теперь «+7» — это неизменяемый префикс поля, а ввод принимает
 * ровно 10 цифр национального номера. Никакой двусмысленности: что набрано,
 * то и записано.
 *
 * Модуль изоморфный: ни DOM, ни Node-специфики, поэтому его импортируют
 * и клиентская форма, и route handler.
 */

/** Код страны. Показывается префиксом, в ввод не входит. */
export const COUNTRY_CODE = '7';
/** Длина национального номера в цифрах (без кода страны). */
export const NATIONAL_LENGTH = 10;

/** Оставляет только цифры: `+7 (700) 123-45-67` → `77001234567`. */
export function phoneDigits(value: string): string {
  return value.replace(/\D/g, '');
}

/**
 * Национальная часть номера: ровно 10 цифр без кода страны.
 *
 *   «700 123 45 67»          → 7001234567
 *   «+7 700 123 45 67»       → 7001234567   (код страны отброшен)
 *   «8 700 123 45 67»        → 7001234567   (привычная запись через 8)
 *   «+7 700 123 45 6O»       → 700123456    (буква отброшена)
 *   «+49 30 123456»          → 4930123456   (обрезано до 10)
 */
export function nationalDigits(value: string): string {
  let digits = phoneDigits(value);
  // Код страны отбрасываем только у ровно одиннадцати цифр: это единственный
  // случай, когда он действительно набран целиком. При «больше одиннадцати»
  // это уже мусор от вставки, и срезать первую цифру нельзя — иначе «70012345678888»
  // терял свою семёрку и превращался в «001 234 56 78».
  if (
    digits.length === NATIONAL_LENGTH + 1 &&
    (digits[0] === COUNTRY_CODE || digits[0] === '8')
  ) {
    digits = digits.slice(1);
  }
  return digits.slice(0, NATIONAL_LENGTH);
}

/** Показ национальной части: `7001234567` → `700 123 45 67`. */
export function formatNational(value: string): string {
  const d = nationalDigits(value);
  if (!d) return '';
  return [d.slice(0, 3), d.slice(3, 6), d.slice(6, 8), d.slice(8, 10)].filter(Boolean).join(' ');
}

/** Полный номер для показа: `7001234567` → `+7 700 123 45 67`. */
export function formatPhone(value: string): string {
  const body = formatNational(value);
  return body ? `+${COUNTRY_CODE} ${body}` : '';
}

/** Значение для формы и для отправки: `+77001234567` либо пустая строка. */
export function canonicalPhone(value: string): string {
  const d = nationalDigits(value);
  return d ? `+${COUNTRY_CODE}${d}` : '';
}

/** Номер набран целиком — 10 цифр национальной части. */
export function isCompletePhone(value: string): boolean {
  return nationalDigits(value).length === NATIONAL_LENGTH;
}

/** Сколько цифр ещё не хватает — для подсказки под полем. */
export function phoneDigitsLeft(value: string): number {
  return Math.max(0, NATIONAL_LENGTH - nationalDigits(value).length);
}
